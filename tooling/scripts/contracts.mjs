import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { generateOpenApi } from "../../apps/api/dist/openapi.js";
import { root } from "./process.mjs";

const require = createRequire(join(root, "apps/api/package.json"));
const codegen = await import(pathToFileURL(require.resolve("openapi-typescript")).href);
const openapiTS = codegen.default.default;
const { astToString } = codegen;
export async function contracts({ check = false } = {}) {
  const schema = await generateOpenApi();
  const outputs = [
    ["packages/contracts/generated/openapi.json", `${JSON.stringify(schema, null, 2)}\n`],
    [
      "packages/api-client/src/generated/schema.ts",
      `// Generated by contracts:generate; do not edit.\n${astToString(await openapiTS(schema))}`,
    ],
  ];
  for (const [file, content] of outputs) {
    const path = join(root, file);
    if (check) {
      if (readFileSync(path, "utf8") !== content) throw new Error(`Contract drift: ${file}`);
    } else {
      mkdirSync(join(path, ".."), { recursive: true });
      writeFileSync(path, content);
    }
  }
  console.log(check ? "Contract drift check passes." : "Generated public schema and client types.");
}
